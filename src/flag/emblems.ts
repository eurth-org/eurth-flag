export interface Emblem {
  id: string;
  name: string;
  group: string;
  width: number;
  height: number;
  path: string;
}

const make = (group: string, list: [string, string, IconDefinition][]): Emblem[] =>
  list.map(([id, name, def]) => {
    const [width, height, , , path] = def.icon;
    return { id, name, group, width, height, path: Array.isArray(path) ? path.join(' ') : path };
  });

